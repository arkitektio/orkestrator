/**
 * hash.ts — the deterministic primitives, with no imports at all.
 *
 * Deliberately its own module: the cache key needs `cyrb53`, and the cache must
 * stay reachable without dragging `three` or the 83 kB of JSON data into the
 * static import graph. Everything downstream of `spec.ts` is dynamically
 * imported; this is not.
 *
 * These are also what make a mark stable — the same identifier must produce the
 * same pose and the same fallback plate forever, so a refactor here silently
 * reshuffles every app's icon. `hash.test.ts` pins golden values for exactly
 * that reason.
 */

export function cyrb53(str: string, seed = 0): number {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

export function mulberry32(a: number): () => number {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
